<#
.SYNOPSIS
    Remove what this stand accumulates, without rebuilding anything.

.DESCRIPTION
    The stand keeps running for days, and several things grow the whole time
    without anybody reading them (FIXES.md, section 17):

      * Loki stores the logs of every pod in an emptyDir and has no retention
        configured, while the triage bot only ever asks for the last 15 minutes
        (LOG_WINDOW_SECONDS);
      * Prometheus keeps a 360h TSDB in an emptyDir - 15 days for a demo;
      * every `deploy.ps1 -WithAIOps` builds and imports `triage-bot:0.1.0-m1`,
        and older layers stay behind in containerd on all three nodes;
      * completed pods pile up (the Grafana import Job is deleted and recreated
        on every deploy) together with their logs and sandboxes.

    This script removes exactly those four things and nothing else. The
    application, the Secrets and the triage bot are untouched, nothing is
    re-pulled, and a run takes about half a minute - which is why it is
    maintenance and not a rebuild.

    It prints disk usage and object counts before and after, so the next time
    something grows there is a measurement instead of a theory.

.PARAMETER KeepPrometheus
    Keep the metric history: skip the Prometheus restart. The TSDB is in an
    emptyDir, so restarting the pod is what frees it.

.PARAMETER KeepLogs
    Keep the Loki data: skip the Loki restart. Use it if you are about to read
    logs from more than a few hours ago.

.PARAMETER DryRun
    Print what would be deleted and change nothing.

.NOTES
    ASCII only and Windows PowerShell 5.1 compatible, like deploy.ps1.
    Safe to run while the stand is up. Nothing here is a production pattern:
    a real cluster gets retention policies, image GC and alerting instead.
#>
[CmdletBinding()]
param(
    [switch]$KeepPrometheus,
    [switch]$KeepLogs,
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot

# The kubeconfig is generated by terraform and carries a port that changes on
# every apply, so it is read from the state rather than assumed.
$kubeconfig = Join-Path $env:USERPROFILE ".kube\sock-shop-k3d.yaml"
$tfDir = Join-Path $repoRoot "terraform\k3d"
if (Get-Command terraform -ErrorAction SilentlyContinue) {
    # Push-Location rather than `terraform -chdir=...`: Windows PowerShell passes
    # the flag to the native binary unexpanded (the same note as in deploy.ps1).
    Push-Location $tfDir
    try {
        $fromTf = & terraform output -raw kubeconfig_path 2>$null
        if ($LASTEXITCODE -eq 0 -and $fromTf) { $kubeconfig = "$fromTf".Trim() }
    } finally {
        Pop-Location
    }
}
if (-not (Test-Path $kubeconfig)) { throw "kubeconfig not found: $kubeconfig (deploy the stand first)" }
$env:KUBECONFIG = $kubeconfig

$nodes = @(docker ps --filter "name=k3d-sock-shop" --format "{{.Names}}" |
    Where-Object { $_ -match '^k3d-sock-shop-(server|agent)-\d+$' })
if ($nodes.Count -eq 0) { throw "no k3d nodes for cluster 'sock-shop' - is the stand running?" }

function Get-Usage {
    param([string]$Node)
    $raw = docker exec $Node sh -c "df -h / | tail -1" 2>&1
    if ($LASTEXITCODE -ne 0) { return "  $Node : unreachable" }
    $fields = ($raw -split '\s+') | Where-Object { $_ }
    $images = (docker exec $Node crictl images -q 2>$null | Measure-Object -Line).Lines
    return ("  {0,-28} {1} used of {2} ({3})  images: {4}" -f $Node, $fields[2], $fields[1], $fields[4], $images)
}

function Write-Step { param([string]$Text) Write-Host ""; Write-Host "==> $Text" -ForegroundColor Cyan }

# kubectl writes "No resources found" to stderr and exits 1 when a selector
# matches nothing - which is a normal answer here, but native stderr under
# $ErrorActionPreference = "Stop" is a terminating error. Same trap, and the same
# answer, as Invoke-QuietProbe in deploy.ps1.
function Invoke-Kubectl {
    param([Parameter(Mandatory)][string[]] $Arguments)
    $previous = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $out = & kubectl @Arguments 2>&1 |
            Where-Object { $_ -isnot [System.Management.Automation.ErrorRecord] }
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previous
    }
    return [pscustomobject]@{ ExitCode = $code; Output = @($out) }
}

Write-Step "Before"
$nodes | ForEach-Object { Write-Host (Get-Usage $_) -ForegroundColor Gray }

$succeeded = @((Invoke-Kubectl -Arguments @("get", "pods", "-A", "--field-selector=status.phase=Succeeded", "--no-headers")).Output |
    Where-Object { "$_".Trim() })
$failed = @((Invoke-Kubectl -Arguments @("get", "pods", "-A", "--field-selector=status.phase=Failed", "--no-headers")).Output |
    Where-Object { "$_".Trim() })
Write-Host ("  finished pods: {0} Succeeded, {1} Failed" -f $succeeded.Count, $failed.Count) -ForegroundColor Gray

if ($DryRun) {
    Write-Step "Dry run - nothing is deleted"
    Write-Host "  would delete: finished pods, unused images on each node, Loki and Prometheus data" -ForegroundColor Yellow
    exit 0
}

# --- 1. Finished pods --------------------------------------------------------
# Their containers, logs and sandboxes are what takes space on the node; the
# objects themselves are only the handle to it.
Write-Step "Finished pods"
foreach ($phase in @("Succeeded", "Failed")) {
    $count = @((Invoke-Kubectl -Arguments @("get", "pods", "-A", "--field-selector=status.phase=$phase", "--no-headers")).Output |
        Where-Object { "$_".Trim() }).Count
    if ($count -eq 0) { Write-Host "  $phase : none" -ForegroundColor Gray; continue }
    $result = Invoke-Kubectl -Arguments @("delete", "pods", "-A", "--field-selector=status.phase=$phase", "--wait=false")
    if ($result.ExitCode -eq 0) {
        Write-Host "  $phase : $count deleted" -ForegroundColor Gray
    } else {
        Write-Host "  $phase : delete failed - $($result.Output -join ' ')" -ForegroundColor Yellow
    }
}

# --- 2. Unused images on every node -----------------------------------------
# `crictl rmi --prune` removes images no container references - the older
# triage-bot layers are exactly that after a rebuild of the same tag.
Write-Step "Unused images"
foreach ($node in $nodes) {
    $before = (docker exec $node crictl images -q 2>$null | Measure-Object -Line).Lines
    $pruned = docker exec $node crictl rmi --prune 2>&1
    $after = (docker exec $node crictl images -q 2>$null | Measure-Object -Line).Lines
    Write-Host ("  {0,-28} images {1} -> {2}" -f $node, $before, $after) -ForegroundColor Gray
}

# --- 3. Loki and Prometheus data --------------------------------------------
# Both keep their data in an emptyDir, so the pod IS the storage: restarting the
# deployment is the delete. Loki's logs are only ever read for the last 15
# minutes by the bot, and Prometheus' 360h of history is a demo convenience.
Write-Step "Time-series and log data"
foreach ($target in @(
    @{ Namespace = "logging";    Name = "loki";                  Skip = $KeepLogs;        What = "log chunks" },
    @{ Namespace = "monitoring"; Name = "prometheus-deployment"; Skip = $KeepPrometheus;  What = "TSDB blocks" }
)) {
    if ($target.Skip) {
        Write-Host ("  {0} : kept (-{1})" -f $target.Name, $(if ($target.Name -eq "loki") { "KeepLogs" } else { "KeepPrometheus" })) -ForegroundColor Gray
        continue
    }
    $restart = Invoke-Kubectl -Arguments @("-n", $target.Namespace, "rollout", "restart", "deployment/$($target.Name)")
    if ($restart.ExitCode -eq 0) {
        Write-Host ("  {0} : restarted, {1} dropped (emptyDir)" -f $target.Name, $target.What) -ForegroundColor Gray
    } else {
        Write-Host ("  {0} : restart failed - {1}" -f $target.Name, ($restart.Output -join ' ')) -ForegroundColor Yellow
    }
}

Write-Step "Waiting for the restarts"
foreach ($target in @("logging/loki", "monitoring/prometheus-deployment")) {
    $parts = $target -split "/"
    $status = Invoke-Kubectl -Arguments @("-n", $parts[0], "rollout", "status", "deployment/$($parts[1])", "--timeout=180s")
    if ($status.ExitCode -eq 0) {
        Write-Host "  $target : ready" -ForegroundColor Gray
    } else {
        Write-Host "  $target : NOT ready - check 'kubectl -n $($parts[0]) get pods'" -ForegroundColor Yellow
    }
}

# --- 4. The bot's journal ----------------------------------------------------
# Append-only JSONL: it is the audit trail, so it is reported, never truncated.
$journalPod = @((Invoke-Kubectl -Arguments @("-n", "monitoring", "get", "pods", "-l", "app.kubernetes.io/name=triage-bot", "--no-headers")).Output) |
    Select-Object -First 1
if ($journalPod) {
    $name = ("$journalPod" -split '\s+')[0]
    $size = Invoke-Kubectl -Arguments @("-n", "monitoring", "exec", $name, "--", "du", "-sk", "/data")
    if ($size.ExitCode -eq 0) {
        Write-Host "  triage-bot journal: $($size.Output -join ' ') (kept - audit trail)" -ForegroundColor Gray
    }
}

Write-Step "After"
$nodes | ForEach-Object { Write-Host (Get-Usage $_) -ForegroundColor Gray }
Write-Host ""
Write-Host "Done. The application, the Secrets and the triage bot were not touched." -ForegroundColor Green
exit 0

